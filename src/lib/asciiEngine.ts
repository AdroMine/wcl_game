// Render any word into a 15-row ASCII matrix with generous, consistent kerning and border margins
export function renderWordToAscii(word: string, kerningSpaces = 2, marginSpaces = 2): string[] {
  const letters = word.toUpperCase().split("");
  const gap = " ".repeat(Math.max(1, kerningSpaces));
  const margin = " ".repeat(Math.max(0, marginSpaces));
  const rows: string[] = Array(15).fill("");
  for (let r = 0; r < 15; r++) {
    rows[r] = margin + letters.map(char => ASCII_FONT_15ROW[char]?.[r] || "        ").join(gap) + margin;
  }
  return rows;
}

// Slice dynamically for ANY team size with ZERO duplicate rows and ZERO missing rows
export function getPlayerAsciiSlice(
  word: string,
  playerSlotIndex: number, // 0 to teamSize - 1
  teamSize: number,
  mode: "HORIZONTAL" | "VERTICAL" = "HORIZONTAL",
  kerningSpaces = 2
): string[] {
  const safeTeamSize = Math.max(1, teamSize);
  const safeSlot = Math.max(0, Math.min(playerSlotIndex, safeTeamSize - 1));
  const baseRows = renderWordToAscii(word, kerningSpaces); // 15 rows high

  if (mode === "HORIZONTAL") {
    // 3 rows per slice for 5-player teams (15 / 5 = 3 rows)
    const rowsPerSlice = Math.max(1, Math.floor(15 / safeTeamSize));
    const targetTotalRows = safeTeamSize * rowsPerSlice;

    // Direct 1-to-1 mapping when teamSize === 5 (15 rows = 15 rows)
    const resampledRows: string[] = [];
    for (let i = 0; i < targetTotalRows; i++) {
      const srcIdx = Math.min(baseRows.length - 1, Math.floor((i / targetTotalRows) * baseRows.length));
      resampledRows.push(baseRows[srcIdx]);
    }

    const startRow = safeSlot * rowsPerSlice;
    const endRow = startRow + rowsPerSlice;
    return resampledRows.slice(startRow, endRow);
  } else {
    // VERTICAL slicing: slice columns across teamSize players
    const totalCols = baseRows[0].length;
    const sliceWidth = Math.max(4, Math.ceil(totalCols / safeTeamSize));
    const startCol = Math.min(
      totalCols - sliceWidth,
      Math.floor((safeSlot * totalCols) / safeTeamSize)
    );
    const endCol = Math.min(totalCols, startCol + sliceWidth);

    return baseRows.map(line => line.slice(startCol, endCol));
  }
}

// Get all slices for all players in a team
export function getAllAsciiSlices(
  word: string,
  teamSize: number,
  mode: "HORIZONTAL" | "VERTICAL" = "HORIZONTAL",
  kerningSpaces = 2
): string[][] {
  const safeSize = Math.max(1, teamSize);
  const slices: string[][] = [];
  for (let i = 0; i < safeSize; i++) {
    slices.push(getPlayerAsciiSlice(word, i, safeSize, mode, kerningSpaces));
  }
  return slices;
}

// Reassemble slices into the full readable ASCII graphic
export function reassembleAsciiWord(slices: string[][]): string[] {
  const reassembled: string[] = [];
  for (const slice of slices) {
    reassembled.push(...slice);
  }
  return reassembled;
}
